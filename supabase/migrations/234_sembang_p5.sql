-- Migration 234: Sembang P5 — push subscriptions, incoming webhooks, bot cards, 250 MB uploads
--
-- What changes:
--   1. Increase sembang-files bucket limit: 16 MB → 250 MB
--   2. sembang_push_subscriptions — per-user VAPID Web Push endpoints
--   3. sembang_webhooks — per-channel incoming webhook tokens (Slack-compatible inbound)
--   4. sembang_messages.cards JSONB — bot card attachments (rich interactive cards)
--   5. NOTIFY trigger on sembang_push_subscriptions so SSE picks up subscription changes

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Raise file size limit on the sembang-files storage bucket
-- ─────────────────────────────────────────────────────────────────────────────
-- Only where Supabase storage exists: the Halo VPS keeps files on disk and has no storage schema.
DO $ BEGIN
  IF to_regclass('storage.buckets') IS NOT NULL THEN
    UPDATE storage.buckets
      SET file_size_limit = 262144000   -- 250 × 1024 × 1024 bytes
      WHERE id = 'sembang-files';
  END IF;
END $;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Web Push subscriptions
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.sembang_push_subscriptions (
  id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id  UUID        NOT NULL REFERENCES public.accounts(id)   ON DELETE CASCADE,
  user_id     UUID        NOT NULL REFERENCES auth.users(id)        ON DELETE CASCADE,
  -- Standard Web Push PushSubscription fields
  endpoint    TEXT        NOT NULL,
  p256dh      TEXT        NOT NULL,
  auth_key    TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, endpoint)
);

CREATE INDEX IF NOT EXISTS sembang_push_subs_account ON public.sembang_push_subscriptions (account_id);
CREATE INDEX IF NOT EXISTS sembang_push_subs_user    ON public.sembang_push_subscriptions (user_id);

ALTER TABLE public.sembang_push_subscriptions ENABLE ROW LEVEL SECURITY;

-- Users manage only their own subscriptions
DROP POLICY IF EXISTS sembang_push_own ON public.sembang_push_subscriptions;
CREATE POLICY sembang_push_own ON public.sembang_push_subscriptions
  USING  (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid() AND public.has_capability(account_id, 'menu.sembang'));

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Incoming webhooks
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.sembang_webhooks (
  id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id  UUID        NOT NULL REFERENCES public.accounts(id)        ON DELETE CASCADE,
  channel_id  UUID        NOT NULL REFERENCES public.sembang_channels(id) ON DELETE CASCADE,
  name        TEXT        NOT NULL,
  -- Unique inbound token; generated by the application (crypto.randomUUID() on creation)
  token       TEXT        NOT NULL UNIQUE,
  is_active   BOOLEAN     NOT NULL DEFAULT true,
  created_by  UUID        REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sembang_webhooks_channel ON public.sembang_webhooks (channel_id);
CREATE INDEX IF NOT EXISTS sembang_webhooks_token   ON public.sembang_webhooks (token);

ALTER TABLE public.sembang_webhooks ENABLE ROW LEVEL SECURITY;

-- Channel members can read webhooks for channels they belong to
DROP POLICY IF EXISTS sembang_webhooks_select ON public.sembang_webhooks;
CREATE POLICY sembang_webhooks_select ON public.sembang_webhooks
  FOR SELECT USING (
    public.has_capability(account_id, 'menu.sembang')
    AND public.is_sembang_channel_member(channel_id)
  );

-- Channel members can create webhooks (they become the creator)
DROP POLICY IF EXISTS sembang_webhooks_insert ON public.sembang_webhooks;
CREATE POLICY sembang_webhooks_insert ON public.sembang_webhooks
  FOR INSERT WITH CHECK (
    created_by = auth.uid()
    AND public.has_capability(account_id, 'menu.sembang')
    AND public.is_sembang_channel_member(channel_id)
  );

-- Only the creator can update or delete
DROP POLICY IF EXISTS sembang_webhooks_update ON public.sembang_webhooks;
CREATE POLICY sembang_webhooks_update ON public.sembang_webhooks
  FOR UPDATE USING (created_by = auth.uid()) WITH CHECK (created_by = auth.uid());

DROP POLICY IF EXISTS sembang_webhooks_delete ON public.sembang_webhooks;
CREATE POLICY sembang_webhooks_delete ON public.sembang_webhooks
  FOR DELETE USING (created_by = auth.uid());

-- ─────────────────────────────────────────────────────────────────────────────
-- 4. Bot cards + bot_name on messages
-- ─────────────────────────────────────────────────────────────────────────────
-- cards JSONB shape (array of card objects):
-- [{
--   "title":     "PR #123 merged",
--   "text":      "main ← feat/login by Alice",
--   "color":     "green" | "red" | "yellow" | "blue" | null,
--   "fields":    [{"title": "Branch", "value": "main"}, ...],
--   "actions":   [{"id": "btn1", "label": "View PR", "style": "primary"|"danger"|"default",
--                  "url": "https://..."}]
-- }]
ALTER TABLE public.sembang_messages
  ADD COLUMN IF NOT EXISTS cards JSONB;

-- bot_name: display name for webhook / bot messages where author_id is NULL
ALTER TABLE public.sembang_messages
  ADD COLUMN IF NOT EXISTS bot_name TEXT;

-- ─────────────────────────────────────────────────────────────────────────────
-- 5. NOTIFY trigger so the SSE layer picks up new push subscriptions
-- ─────────────────────────────────────────────────────────────────────────────
DO $$ BEGIN
  DROP TRIGGER IF EXISTS halo_rt_sembang_push_subs ON public.sembang_push_subscriptions;
END $$;

CREATE TRIGGER halo_rt_sembang_push_subs
  AFTER INSERT OR UPDATE OR DELETE ON public.sembang_push_subscriptions
  FOR EACH ROW EXECUTE FUNCTION halo_notify_account_change();
