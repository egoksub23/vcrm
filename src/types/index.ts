/**
 * One row of `list_sembang_channels_for_current_user` — the sidebar's
 * channel list (GET /api/sembang/channels), already unread-counted.
 */
export interface SembangChannelSummary {
  id: string;
  name: string | null;
  topic: string | null;
  isPrivate: boolean;
  /** Migration 100. See `SembangChannel.isDm`. */
  isDm: boolean;
  createdBy: string;
  createdAt: string;
  memberRole: SembangMemberRole;
  lastReadAt: string;
  unreadCount: number;
  lastMessageBody: string | null;
  lastMessageAt: string | null;
  lastMessageAuthorId: string | null;
  /** Migration 100. Only populated when `isDm` is true — the OTHER
   *  participant(s), for rendering a DM row's display name/avatars
   *  without a second fetch. Null (not empty array) for a real channel. */
  dmParticipantNames: string[] | null;
  dmParticipantAvatarUrls: (string | null)[] | null;
  /** Migration 101. The caller's own mute state — see `SembangChannel.muted`. */
  muted: boolean;
  /** Unread `sembang_mention`/`sembang_dm_message` notifications for this
   *  channel — a subset of `unreadCount` (every unread message counts
   *  toward `unreadCount`, only ones that @mentioned the caller or were a
   *  DM count here too). Task-assignment notifications are excluded —
   *  those already have their own per-channel Tasks affordance. */
  unreadMentionCount: number;
}

