export type ConversationStatus = 'open' | 'pending' | 'closed';

/** Migration 047. Sorts/badges in the inbox; set manually from the
 *  thread header or via the `set_priority` automation step (e.g. a
 *  condition on a "VIP" custom field → set_priority: urgent). */
export type ConversationPriority = 'urgent' | 'high' | 'normal' | 'low';

/** Which channel a given message came in/went out on. Introduced in
 *  migration 046 as a whole-conversation property, then moved down to
 *  the message level in migration 048 once a single conversation could
 *  span both channels (WhatsApp + Web Widget merged by contact).
 *  Messenger and Instagram added in migration 055; Email (Microsoft 365
 *  / Outlook, via Microsoft Graph) added in migration 056; Gmail added
 *  in migration 058 — kept distinct from `'email'` even though both are
 *  "email", since an account may connect one, the other, or both (e.g.
 *  support@ on Gmail and sales@ on Microsoft 365), same reasoning
 *  Messenger/Instagram stay distinct despite both being Meta.
 *  WhatsApp-only send affordances (templates, interactive buttons/lists)
 *  only make sense for `'whatsapp'` — see send-message.ts and the
 *  automation engine's per-step channel guards. */
export type ChannelType = 'whatsapp' | 'web_widget' | 'messenger' | 'instagram' | 'email' | 'gmail';

export interface Conversation {
  id: string;
  user_id: string;
  contact_id: string;
  status: ConversationStatus;
  /** Rollup of the most recent message's channel (migration 048) — a
   *  merged conversation can contain messages from both channels, so
   *  this (not a fixed per-conversation channel) is what UI badges show
   *  and what an agent's reply defaults to sending on. */
  last_channel_type: ChannelType;
  priority: ConversationPriority;
  assigned_agent_id?: string;
  /** Team a conversation is routed to (migration 043); orthogonal to
   *  `assigned_agent_id` — a team assignment always resolves to a
   *  specific agent, but the team pointer is kept so the inbox can
   *  bucket/filter by team. */
  assigned_team_id?: string | null;
  /** Conversation-level topic labels (migration 044) — reuses the same
   *  `tags` palette as contact tags, joined via `conversation_labels`.
   *  Independent of `contact.tags`: labelling "billing issue" on this
   *  conversation doesn't tag the contact, since the same contact may
   *  have unrelated conversations later. */
  labels?: Tag[];
  last_message_text?: string;
  last_message_at?: string;
  /** True from the moment a customer message arrives until the next
   *  reply on either channel (migration 049) — drives the Inbox's
   *  "aging response" indicator. */
  awaiting_response: boolean;
  /** When the customer's most recent message arrived — independent of
   *  `last_message_at`, which reflects ANY message including our own
   *  replies. Null for a conversation with no customer message yet. */
  last_customer_message_at?: string | null;
  /** When this conversation was most recently closed (migration 050) —
   *  null while open/pending, cleared on reopen. Powers the Resolutions
   *  report's open→closed duration; rows closed before this migration
   *  are backfilled from `updated_at` as an approximation. */
  closed_at?: string | null;
  unread_count: number;
  created_at: string;
  updated_at: string;
  contact?: Contact;
  /**
   * AI auto-reply state for this thread (migration 029 + 033):
   *  - `ai_autoreply_disabled` — the bot is paused here (a human took
   *    over, or the model handed off). Sticky until re-enabled.
   *  - `ai_reply_count` — how many times the bot has auto-replied,
   *    checked against the account's per-conversation cap.
   *  - `ai_handoff_summary` — short internal note the bot wrote when it
   *    handed off, shown to whoever takes the thread over.
   */
  ai_autoreply_disabled?: boolean;
  ai_reply_count?: number;
  ai_handoff_summary?: string | null;
}

