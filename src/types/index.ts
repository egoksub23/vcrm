export interface SembangMessage {
  id: string;
  channelId: string;
  accountId: string;
  authorId: string;
  body: string;
  /** Plain array of mentioned user-id strings (not objects). */
  mentions: string[];
  /** Migration 099. Set only on a top-level message that is itself a
   *  thread reply's parent — threads are flat, one level, so a reply's
   *  own `parentMessageId` never points at another reply. */
  parentMessageId: string | null;
  /** Migration 099. Set once the author edits the body. */
  editedAt: string | null;
  deletedAt: string | null;
  deletedBy: string | null;
  createdAt: string;
  /** Joined from `profiles`; null if the author's profile was removed. */
  author: { id: string; fullName: string; avatarUrl: string | null } | null;
  attachments: SembangAttachment[];
  /** Migration 099. Empty array when the message has none. */
  reactions: SembangReactionSummary[];
  /** Migration 100. Personal — whether the CALLER has starred this
   *  message, precomputed server-side (same shape as `reactedByMe`). */
  starredByMe: boolean;
  /**
   * Migration 099. Only populated on TOP-LEVEL messages (parentMessageId
   * null) by the channel message list — a reply row leaves these
   * undefined rather than computing them for something that can't itself
   * have replies (threads are flat).
   */
  replyCount?: number;
  lastReplyAt?: string | null;
  /** Migration 101. Only meaningful when `parentMessageId` is set — a
   *  reply the author chose to also post into the main channel
   *  timeline (Slack's "Also send to #channel"), immutable after
   *  creation. False for a normal thread-only reply. */
  alsoInChannel: boolean;
  /** Migration 101. Populated whenever `parentMessageId` is set, so a
   *  reply rendered in the main timeline (because `alsoInChannel`) can
   *  show "replied to a thread: <snippet>" without a second fetch.
   *  Null for a top-level message; also null if the parent itself was
   *  deleted/not found. */
  parentPreview?: { id: string; body: string; authorName: string } | null;
}

